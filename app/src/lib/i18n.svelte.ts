const DICTS: Record<Locale, Dict> = { cs, sk, en, de };

function initial(): Locale {
  try {
    const saved = localStorage.getItem("tectora.locale") as Locale | null;
    if (saved && saved in DICTS) return saved;
  } catch {
    // Storage unavailable: fall back to the system language.
  }
  const sys = (navigator.language || "cs").slice(0, 2);
  return (sys in DICTS ? sys : "cs") as Locale;
}

export const i18n = $state({ locale: initial() });

export function setLocale(l: Locale) {
  i18n.locale = l;
  try {
    localStorage.setItem("tectora.locale", l);
  } catch {
    // Not persisted; the choice still applies for this session.
  }
  document.documentElement.lang = l;
}

/** Translates `key`, filling `{name}` placeholders from `params`. */
export function t(key: string, params: Record<string, string | number> = {}): string {
  const s = DICTS[i18n.locale][key] ?? cs[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => String(params[k] ?? `{${k}}`));
}

