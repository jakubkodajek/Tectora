//! Canonical composition (Unicode NFC) of the letters job, file and
//! search names use. macOS hands over names in decomposed form (NFD:
//! `u` + combining ring for `ů`, from a file name or the clipboard), while
//! everything typed elsewhere is precomposed; without composing first, the
//! same name gives two ids, a search misses it and one job holds two files
//! that look the same (audit 2026-11-21 HUNTIO-007).
//!
//! No dependency: the table covers the precomposed letters of Latin-1,
//! Latin Extended-A and -B, Latin Extended Additional and Cyrillic (every
//! European language), generated from Python's `unicodedata`
//! (`decomposition` of two code points whose NFC is the letter itself).
//! Marks after other letters are kept as they are.

use std::borrow::Cow;

/// `s` with each base letter and combining mark the table knows composed
/// into one character, applied repeatedly (`u` + diaeresis + acute is `ǘ`).
pub fn nfc(s: &str) -> Cow<'_, str> {
    if !s.chars().any(is_mark) {
        return Cow::Borrowed(s);
    }
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        if is_mark(c)
            && let Some(last) = out.chars().next_back()
            && let Some(composed) = compose(last, c)
        {
            out.pop();
            out.push(composed);
        } else {
            out.push(c);
        }
    }
    Cow::Owned(out)
}

/// The letter `c` is made of without its marks (`ő` -> `o`, `ǘ` -> `u`,
/// `ș` -> `s`), for a font that has no glyph for it; `None` for a
/// character that is no precomposed letter of the table.
pub fn base_letter(c: char) -> Option<char> {
    let mut base = COMPOSE.iter().find(|e| e.2 == c)?.0;
    while let Some(e) = COMPOSE.iter().find(|e| e.2 == base) {
        base = e.0;
    }
    Some(base)
}

/// A combining mark the table composes (U+0300 to U+036F).
fn is_mark(c: char) -> bool {
    ('\u{300}'..='\u{36f}').contains(&c)
}

fn compose(base: char, mark: char) -> Option<char> {
    COMPOSE
        .binary_search_by(|&(b, m, _)| (b, m).cmp(&(base, mark)))
        .ok()
        .map(|i| COMPOSE[i].2)
}

