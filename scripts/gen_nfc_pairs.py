#!/usr/bin/env python3
"""Writes crates/tectora-core/src/nfc_pairs.rs: every canonical composition
pair of Unicode NFC (a primary composite that is no composition exclusion)
that the hand-kept table `COMPOSE` in crates/tectora-core/src/nfc.rs does
not have: marks outside U+0300 to U+036F (Arabic madda U+0653, kana voicing
U+3099, ...) and vowel signs that compose with the letter before them.
Hangul syllables are composed by the algorithm in nfc.rs, not listed. With
them the core composes as the app's `String.prototype.normalize("NFC")`
does (audit 2026-11-22 HUNT-701, TEST-710).
Run: python3 scripts/gen_nfc_pairs.py
"""
import pathlib
import re
import unicodedata

root = pathlib.Path(__file__).resolve().parent.parent
nfc_rs = (root / "crates/tectora-core/src/nfc.rs").read_text()
known = {
    (int(a, 16), int(b, 16))
    for a, b in re.findall(r"\('\\u\{([0-9a-f]+)\}', '\\u\{([0-9a-f]+)\}', '\\u\{[0-9a-f]+\}'\)", nfc_rs)
}
rows = []
for cp in range(0x20, 0x110000):
    if 0xD800 <= cp < 0xE000 or 0xAC00 <= cp <= 0xD7A3:
        continue
    d = unicodedata.decomposition(chr(cp))
    if not d or d.startswith("<"):
        continue
    parts = [int(x, 16) for x in d.split()]
    if len(parts) != 2:
        continue
    # A composition exclusion does not come back from its pair.
    if unicodedata.normalize("NFC", chr(parts[0]) + chr(parts[1])) != chr(cp):
        continue
    if tuple(parts) in known:
        continue
    rows.append((parts[0], parts[1], cp))
rows.sort()
text = (
    "//! Generated by `scripts/gen_nfc_pairs.py` from Unicode "
    f"{unicodedata.unidata_version}; do not edit.\n"
    "//! Canonical composition pairs `nfc::COMPOSE` does not have:\n"
    "//! (first, second, composed), sorted by first and second.\n\n"
    "#[rustfmt::skip]\n"
    "pub(crate) const PAIRS: &[(char, char, char)] = &[\n"
    + "".join(f"    ('\\u{{{a:x}}}', '\\u{{{b:x}}}', '\\u{{{c:x}}}'),\n" for a, b, c in rows)
    + "];\n\n"
    "/// The second characters of [`PAIRS`], sorted.\n"
    "#[rustfmt::skip]\n"
    "pub(crate) const SECONDS: &[char] = &[\n"
    + "".join(f"    '\\u{{{b:x}}}',\n" for b in sorted({r[1] for r in rows}))
    + "];\n\n"
    "/// The canonical combining class of every character whose class is not\n"
    "/// 0, sorted: marks are put in this order before they compose\n"
    "/// (canonical reordering, audit 2026-11-22 HUNT-803).\n"
    "#[rustfmt::skip]\n"
    "pub(crate) const CCC: &[(char, u8)] = &[\n"
    + "".join(
        f"    ('\\u{{{cp:x}}}', {unicodedata.combining(chr(cp))}),\n"
        for cp in range(0x20, 0x110000)
        if not (0xD800 <= cp < 0xE000) and unicodedata.combining(chr(cp))
    )
    + "];\n"
)
(root / "crates/tectora-core/src/nfc_pairs.rs").write_text(text)

# Inputs of the fold parity file (TEST-710): the canonical decomposition of
# every code point whose NFD has a character outside U+0300 to U+036F after
# its first, Hangul syllables left out (the parity tests make those).
seqs = []
for cp in range(0x20, 0x30000):
    if 0xD800 <= cp < 0xE000 or 0xAC00 <= cp <= 0xD7A3:
        continue
    d = unicodedata.normalize("NFD", chr(cp))
    if d != chr(cp) and any(not (0x300 <= ord(x) <= 0x36F) for x in d[1:]):
        seqs.append(d)
# A mark between a letter and the mark it composes with, in an order NFC
# changes: canonical reordering comes before composition (HUNT-803).
seqs += [
    "\u0627\u064b\u0653",  # alef + fathatan + madda: alef with madda, fathatan
    "\u304b\u0301\u3099",  # ka + acute + voicing mark: ga, acute
    "\u0928\u0951\u093c",  # na + udatta + nukta: nnna, udatta
    "e\u0302\u0323",  # e + circumflex + dot below: e with both
    "o\u0301\u031b",  # o + acute + horn: o with horn and acute
    "\u00e9\u0323",  # e with acute + dot below
]
import json
(root / "tests/fixtures/parity/nfc_inputs.json").write_text(
    json.dumps(
        {
            "_comment": f"Generated by scripts/gen_nfc_pairs.py from Unicode {unicodedata.unidata_version}: decomposed sequences with a mark outside U+0300-036F; inputs of the fold parity tests (library.rs parity_inputs, app/src/lib/fold.test.ts).",
            "inputs": seqs,
        },
        ensure_ascii=True,
        indent=0,
    )
    + "\n"
)
print(f"{len(seqs)} decomposed inputs -> tests/fixtures/parity/nfc_inputs.json")
print(f"{len(rows)} pairs -> crates/tectora-core/src/nfc_pairs.rs")
