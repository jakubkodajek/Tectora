#!/usr/bin/env python3
"""Writes crates/tectora-core/src/nfc_singletons.rs: every code point that
Unicode NFC changes on its own (canonical singletons such as the Greek oxia
vowels U+1F71, and composition exclusions such as U+0958), with its NFC
form. The core's `nfc::nfc` applies them, so the core folds as the app's
`String.prototype.normalize("NFC")` does (audit 2026-11-22 HUNT-602,
TEST-608). Run: python3 scripts/gen_nfc_singletons.py
"""
import pathlib
import unicodedata

out = pathlib.Path(__file__).resolve().parent.parent / "crates/tectora-core/src/nfc_singletons.rs"
rows = []
for cp in range(0x20, 0x110000):
    if 0xD800 <= cp < 0xE000:
        continue
    c = chr(cp)
    n = unicodedata.normalize("NFC", c)
    if n != c:
        to = "".join(f"\\u{{{ord(x):x}}}" for x in n)
        rows.append(f"    ('\\u{{{cp:x}}}', \"{to}\"),\n")
text = (
    "//! Generated by `scripts/gen_nfc_singletons.py` from Unicode "
    f"{unicodedata.unidata_version}; do not edit.\n"
    "//! Code points NFC changes on their own, with their NFC form, sorted.\n\n"
    "#[rustfmt::skip]\n"
    "pub(crate) const SINGLETONS: &[(char, &str)] = &[\n"
    + "".join(rows)
    + "];\n"
)
out.write_text(text)
print(f"{len(rows)} code points -> {out}")
